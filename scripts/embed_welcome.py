"""Turns the files in welcome/ into src/welcome_text.h: the files on the
drive's welcome disk (src/welcome_disk.*), README.TXT first, as
HDDSynthPro's script does. PlatformIO runs it before each build
(extra_scripts in platformio.ini), and test/run_native_tests.sh before the
host tests. The header is git-ignored, like the .pio.h files.

Each file's name must be a DOS one (8.3, capitals). Its text must be plain
ASCII, so DOS and every other computer show it the same, with lines of at
most 80 characters (DOS's screen). Line endings become CRLF, which DOS
needs. {VERSION} becomes FIRMWARE_VERSION from src/version.h. The files'
date on the disk is the newest of their modification dates.

Usage: python3 scripts/embed_welcome.py [project folder]
"""
from __future__ import annotations

import datetime
import os
import re
import sys

MAX_LINE = 80
MAX_BYTES = 64 * 1024  # each lives in flash; a file this long is a mistake
DOS_NAME = re.compile(r"^[A-Z0-9_-]{1,8}(\.[A-Z0-9_-]{1,3})?$")


def fat_date(day: datetime.date) -> int:
    """FAT's date format: (year - 1980) << 9 | month << 5 | day."""
    return (day.year - 1980) << 9 | day.month << 5 | day.day


def c_string(line: str) -> str:
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\r\\n"'


def text_of(source: str, version: str) -> list[str]:
    with open(source, "rb") as f:
        raw = f.read()
    if len(raw) > MAX_BYTES:
        raise ValueError(f"{source}: {len(raw)} bytes; at most {MAX_BYTES}")
    lines = raw.replace(b"\r\n", b"\n").split(b"\n")
    if lines and lines[-1] == b"":
        lines.pop()  # the final newline
    text = []
    for number, line in enumerate(lines, 1):
        bad = [b for b in line if not (0x20 <= b <= 0x7E)]
        if bad:
            raise ValueError(f"{source}:{number}: only plain ASCII text, no tabs "
                             f"(found byte {bad[0]:#04x})")
        line = line.decode("ascii").replace("{VERSION}", version)
        if len(line) > MAX_LINE:
            raise ValueError(f"{source}:{number}: {len(line)} characters; at most {MAX_LINE}")
        text.append(line)
    return text


def build(project: str) -> str:
    """Writes the header if its content changed; returns its path."""
    folder = os.path.join(project, "welcome")
    header = os.path.join(project, "src", "welcome_text.h")
    with open(os.path.join(project, "src", "version.h"), encoding="ascii") as f:
        version = re.search(r'#define FIRMWARE_VERSION "([^"]+)"', f.read()).group(1)
    names = sorted(n for n in os.listdir(folder) if not n.startswith("."))
    if "README.TXT" not in names:
        raise ValueError(f"{folder}: no README.TXT")
    names.remove("README.TXT")
    names.insert(0, "README.TXT")  # first: what a directory listing shows first
    for name in names:
        if not DOS_NAME.match(name):
            raise ValueError(f"{folder}/{name}: not a DOS file name (8.3, capitals)")

    newest = max(os.path.getmtime(os.path.join(folder, n)) for n in names)
    date = datetime.date.fromtimestamp(newest)
    arrays, entries = [], []
    for name in names:
        ident = re.sub(r"\W", "_", name)
        text = text_of(os.path.join(folder, name), version)
        body = "\n".join(f"    {c_string(line)}" for line in text) or '    ""'
        arrays.append(f"constexpr char {ident}[] =\n{body};\n")
        entries.append(f'    {{"{name}", {ident}, sizeof {ident} - 1}},')
    content = (
        "// Generated by scripts/embed_welcome.py from the files in welcome/: edit\n"
        "// those, not this.\n"
        "#pragma once\n"
        "\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n"
        "\n"
        '#include "welcome_disk.h"\n'
        "\n"
        "namespace welcome_text {\n"
        "\n"
        f"constexpr uint16_t FAT_DATE = {fat_date(date):#06x};  // {date.isoformat()}\n"
        "\n"
        + "\n".join(arrays)
        + "\n"
        "constexpr welcome_disk::File FILES[] = {\n"
        + "\n".join(entries)
        + "\n};\n"
        "constexpr size_t FILE_COUNT = sizeof FILES / sizeof FILES[0];\n"
        "\n"
        "}  // namespace welcome_text\n"
    )
    try:
        with open(header, encoding="ascii") as f:
            if f.read() == content:
                return header
    except FileNotFoundError:
        pass
    with open(header, "w", encoding="ascii", newline="\n") as f:
        f.write(content)
    return header


if __name__ == "__main__":
    try:
        build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), ".."))
    except ValueError as e:
        sys.exit(f"embed_welcome: {e}")
else:
    Import("env")  # noqa: F821 (PlatformIO's SCons runs this before each build)
    try:
        build(env.subst("$PROJECT_DIR"))  # noqa: F821
    except ValueError as e:
        print(f"embed_welcome: {e}")
        env.Exit(1)  # noqa: F821
